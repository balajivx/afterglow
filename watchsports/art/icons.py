HERE = os.path.dirname(os.path.abspath(__file__))


def _simplify(pts, eps):
    """Douglas-Peucker: drop points closer than [eps] to the line between their neighbours."""
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    n = math.hypot(dx, dy) or 1e-9
    far, idx = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / n
        if d > far:
            far, idx = d, i
    if far <= eps:
        return [pts[0], pts[-1]]
    return _simplify(pts[:idx + 1], eps)[:-1] + _simplify(pts[idx:], eps)


def track(cid, size=24.0, pad=2.2):
    """The circuit's outline in a [size] square (north up), simplified for a small icon."""
    import json
    g = json.load(open(os.path.join(HERE, "circuits", CIRCUITS[cid] + ".geojson")))["features"][0]["geometry"]
    pts = g["coordinates"] if g["type"] == "LineString" else g["coordinates"][0]
    lat0 = sum(p[1] for p in pts) / len(pts)
    xy = [(p[0] * math.cos(math.radians(lat0)), -p[1]) for p in pts]
    xs, ys = [p[0] for p in xy], [p[1] for p in xy]
    w, h = max(xs) - min(xs), max(ys) - min(ys)
    k = (size - 2 * pad) / max(w, h)
    ox, oy = pad + ((size - 2 * pad) - w * k) / 2, pad + ((size - 2 * pad) - h * k) / 2
    out = [(ox + (x - min(xs)) * k, oy + (y - min(ys)) * k) for x, y in xy]
    # A lap ends where it starts: simplify it as two halves, split at the point farthest from the start.
    far = max(range(len(out)), key=lambda i: math.hypot(out[i][0] - out[0][0], out[i][1] - out[0][1]))
    return _simplify(out[:far + 1], 0.12)[:-1] + _simplify(out[far:], 0.12)


def track_vector(cid, stroke):
    pts = track(cid)
    data = "M" + " L".join("%.2f,%.2f" % p for p in pts) + " Z"
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by art/icons.py: {cid} ({CIRCUITS[cid]}, bacinger/f1-circuits, MIT). White; tinted where shown. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
            f'    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="{stroke}" android:strokeLineJoin="round"\n'
            f'        android:strokeLineCap="round" android:fillColor="#00000000"\n'
            f'        android:pathData="{data}" />\n</vector>\n')


def draw_track(img, cid, box, rgba, stroke=2.4):
    """The circuit drawn like its vector, for previews."""
    from PIL import Image, ImageDraw
    x, y, size = box
    k = 8
    s = size * k / 24.0
    layer = Image.new("L", (size * k, size * k), 0)
    pts = [(px * s, py * s) for px, py in track(cid)]
    ImageDraw.Draw(layer).line(pts + [pts[0]], fill=255, width=max(1, round(stroke * s)), joint="curve")
    layer = layer.resize((size, size), Image.LANCZOS)
    ink = Image.new("RGBA", (size, size), rgba)
    ink.putalpha(Image.eval(layer, lambda a: a * rgba[3] // 255))
    img.alpha_composite(ink, (x, y))


