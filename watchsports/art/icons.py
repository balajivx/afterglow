"""The widget's three sport icons, defined once as shapes on a 24x24 grid.

    python3 art/icons.py app/src/main/res/drawable     # writes ic_cricket.xml, ic_football.xml, ic_f1.xml,
                                                        # and ic_track_<circuitId>.xml / track_<circuitId>.xml

The watch face tints them (they are drawn white, as monochrome widget images). draw() renders the same shapes
with PIL, for the face's previews (~/Afterglow/watchface/art), so a preview shows what the watch will draw.
Each icon is a list of layers; a layer is (fill shapes, hole shapes). Shapes: ("circle", cx, cy, r) or
("poly", [(x, y), ...]).
"""
import math
import os
import sys


def _quad(x1, y1, x2, y2, w):
    """A bar of width [w] from (x1, y1) to (x2, y2)."""
    dx, dy = x2 - x1, y2 - y1
    n = math.hypot(dx, dy)
    ox, oy = -dy / n * w / 2, dx / n * w / 2
    return ("poly", [(x1 + ox, y1 + oy), (x2 + ox, y2 + oy), (x2 - ox, y2 - oy), (x1 - ox, y1 - oy)])


def _cricket():
    # A red ball (filled) with its raised seam across the diagonal, cut out as two thin lines.
    d = 1.35  # each seam line's offset from the diagonal
    seams = []
    for s in (-1, 1):
        ox, oy = s * d / math.sqrt(2), s * d / math.sqrt(2)  # across the diagonal
        seams.append(_quad(6.2 + ox, 17.8 + oy, 17.8 + ox, 6.2 + oy, 0.9))
    return [([("circle", 12, 12, 9.5)], seams)]


def _football():
    # A filled ball with the classic panels cut out: a centre pentagon, five more at the rim, and the seams
    # running out between them.
    def pentagon(cx, cy, r, turn):
        return ("poly", [(cx + r * math.sin(math.radians(a + turn)), cy - r * math.cos(math.radians(a + turn)))
                         for a in range(0, 360, 72)])
    holes = [pentagon(12, 12, 3.3, 0)]
    for k in range(5):
        a = math.radians(k * 72)
        vx, vy = 12 + 3.3 * math.sin(a), 12 - 3.3 * math.cos(a)
        px, py = 12 + 8.9 * math.sin(a), 12 - 8.9 * math.cos(a)
        holes.append(pentagon(px, py, 2.7, k * 72 + 36))
        holes.append(_quad(vx, vy, px, py, 0.75))
    return [([("circle", 12, 12, 9.8)], holes)]


def _f1():
    # A chequered flag on a pole: a 4 x 2 grid, alternate squares filled, inside a thin frame.
    x0, y0, cw, ch = 6.6, 3.6, 3.5, 4.2
    cells = []
    for r in range(2):
        for c in range(4):
            if (r + c) % 2 == 0:
                cells.append(("poly", [(x0 + c * cw, y0 + r * ch), (x0 + (c + 1) * cw, y0 + r * ch),
                                       (x0 + (c + 1) * cw, y0 + (r + 1) * ch), (x0 + c * cw, y0 + (r + 1) * ch)]))
    x1, y1 = x0 + 4 * cw, y0 + 2 * ch
    frame_out = ("poly", [(x0, y0), (x1, y0), (x1, y1), (x0, y1)])
    frame_in = ("poly", [(x0 + .8, y0 + .8), (x1 - .8, y0 + .8), (x1 - .8, y1 - .8), (x0 + .8, y1 - .8)])
    pole = ("poly", [(4.2, 2.6), (6.2, 2.6), (6.2, 21.4), (4.2, 21.4)])
    return [([frame_out], [frame_in]), (cells, []), ([pole], [])]


ICONS = {"cricket": _cricket(), "football": _football(), "f1": _f1()}


# ---- Android vector drawables

def _path(shape):
    if shape[0] == "circle":
        _, cx, cy, r = shape
        return "M%.2f,%.2f a%.2f,%.2f 0 1,0 %.2f,0 a%.2f,%.2f 0 1,0 %.2f,0 Z" % (cx - r, cy, r, r, 2 * r, r, r, -2 * r)
    pts = shape[1]
    return "M" + " L".join("%.2f,%.2f" % p for p in pts) + " Z"


def vector(name):
    paths = []
    for fills, holes in ICONS[name]:
        data = " ".join(_path(s) for s in fills + holes)
        rule = ' android:fillType="evenOdd"' if holes else ""
        paths.append(f'    <path android:fillColor="#FFFFFFFF"{rule}\n        android:pathData="{data}" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by art/icons.py ({name}): the widget\'s sport icon, white for the face to tint. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
            + "\n".join(paths) + "\n</vector>\n")


# ---- The same, drawn with PIL (for previews)

def draw(img, name, box, rgba):
    """Draws icon [name] into [box] (x, y, size) of RGBA image [img], in colour [rgba]."""
    from PIL import Image, ImageDraw
    x, y, size = box
    k = 8
    big = size * k / 24.0
    mask = Image.new("L", (size * k, size * k), 0)

    for fills, holes in ICONS[name]:
        layer = Image.new("L", mask.size, 0)
        dl = ImageDraw.Draw(layer)
        for s in fills:
            if s[0] == "circle":
                _, cx, cy, r = s
                dl.ellipse(((cx - r) * big, (cy - r) * big, (cx + r) * big, (cy + r) * big), fill=255)
            else:
                dl.polygon([(px * big, py * big) for px, py in s[1]], fill=255)
        for s in holes:
            if s[0] == "circle":
                _, cx, cy, r = s
                dl.ellipse(((cx - r) * big, (cy - r) * big, (cx + r) * big, (cy + r) * big), fill=0)
            else:
                dl.polygon([(px * big, py * big) for px, py in s[1]], fill=0)
        mask = Image.composite(Image.new("L", mask.size, 255), mask, layer)
    mask = mask.resize((size, size), Image.LANCZOS)
    ink = Image.new("RGBA", (size, size), rgba)
    ink.putalpha(Image.eval(mask, lambda a: a * rgba[3] // 255))
    img.alpha_composite(ink, (x, y))


